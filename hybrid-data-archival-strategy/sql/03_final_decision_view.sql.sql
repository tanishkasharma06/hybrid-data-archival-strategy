CREATE OR REPLACE VIEW FINAL_HYBRID_ARCHIVAL_DECISION AS
SELECT READING_ID, DATA_SIZE, LAST_ACCESSED, DAYS_SINCE_ACCESS, ACCESS_COUNT_100D, ACCESS_FREQUENCY, RECORD_STORAGE_UTILISATION, H_SCORE, CASE WHEN H_SCORE >= 2.5 THEN 'ARCHIVE' ELSE 'KEEP' END AS HYBRID_DECISION FROM HYBRID_ARCHIVAL_NEW;

SELECT HYBRID_DECISION, COUNT(*) AS RECORD_COUNT, ROUND(SUM(DATA_SIZE) / 1024 / 1024, 4) AS STORAGE_MB FROM FINAL_HYBRID_ARCHIVAL_DECISION
GROUP BY HYBRID_DECISION
ORDER BY HYBRID_DECISION;

SELECT READING_ID, DATA_SIZE, DAYS_SINCE_ACCESS, ACCESS_COUNT_100D, ROUND(ACCESS_FREQUENCY, 4) AS ACCESS_FREQUENCY, ROUND(RECORD_STORAGE_UTILISATION, 6) AS STORAGE_UTILISATION, ROUND(H_SCORE, 4) AS H_SCORE, HYBRID_DECISION FROM FINAL_HYBRID_ARCHIVAL_DECISION
ORDER BY H_SCORE DESC
FETCH FIRST 10 ROWS ONLY;

SELECT READING_ID, DATA_SIZE, DAYS_SINCE_ACCESS, ACCESS_COUNT_100D, ROUND(ACCESS_FREQUENCY, 4) AS ACCESS_FREQUENCY, ROUND(RECORD_STORAGE_UTILISATION, 6) AS STORAGE_UTILISATION, ROUND(H_SCORE, 4) AS H_SCORE, HYBRID_DECISION FROM FINAL_HYBRID_ARCHIVAL_DECISION
WHERE H_SCORE BETWEEN 2.3 AND 2.7
ORDER BY H_SCORE DESC;

SELECT READING_ID, DATA_SIZE, DAYS_SINCE_ACCESS, ACCESS_COUNT_100D, ROUND(ACCESS_FREQUENCY, 4) AS ACCESS_FREQUENCY, ROUND(RECORD_STORAGE_UTILISATION, 6) AS STORAGE_UTILISATION, ROUND(H_SCORE, 4) AS H_SCORE, HYBRID_DECISION FROM FINAL_HYBRID_ARCHIVAL_DECISION
WHERE ACCESS_COUNT_100D > 0
ORDER BY H_SCORE
FETCH FIRST 10 ROWS ONLY;

SELECT 'TIME-BASED' AS STRATEGY, COUNT(*) AS TOTAL_ARCHIVED, SUM(CASE WHEN ACCESS_COUNT_100D = 0 THEN 1 ELSE 0 END) AS COLD_ARCHIVED, SUM(CASE WHEN ACCESS_COUNT_100D > 0 THEN 1 ELSE 0 END) AS ACTIVE_ARCHIVED, ROUND(100 * SUM(CASE WHEN ACCESS_COUNT_100D = 0 THEN 1 ELSE 0 END) / 18418, 2) AS COLD_CAPTURE_RATE FROM FINAL_HYBRID_ARCHIVAL_DECISION
WHERE DAYS_SINCE_ACCESS >= 230
UNION ALL
SELECT 'HYBRID', COUNT(*), SUM(CASE WHEN ACCESS_COUNT_100D = 0 THEN 1 ELSE 0 END), SUM(CASE WHEN ACCESS_COUNT_100D > 0 THEN 1 ELSE 0 END), ROUND( 100 * SUM(CASE WHEN ACCESS_COUNT_100D = 0 THEN 1 ELSE 0 END) / 18418, 2) FROM FINAL_HYBRID_ARCHIVAL_DECISION
WHERE HYBRID_DECISION = 'ARCHIVE';

SELECT ROUND(100 * (95.07 - 88.0715) / 88.0715, 4) AS RELATIVE_IMPROVEMENT_PERCENT, ROUND(95.07 - 88.0715, 4) AS PERCENTAGE_POINT_IMPROVEMENT FROM DUAL;

SELECT READING_ID, DAYS_SINCE_ACCESS AS AGE_DAYS, ACCESS_FREQUENCY, RECORD_STORAGE_UTILISATION AS U_I, ROUND(H_SCORE, 4) AS H_SCORE, HYBRID_DECISION
FROM FINAL_HYBRID_ARCHIVAL_DECISION
FETCH FIRST 10 ROWS ONLY;
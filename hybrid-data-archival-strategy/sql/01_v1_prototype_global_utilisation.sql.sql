SELECT s.READING_ID, TRUNC(SYSDATE - CAST(s.LAST_ACCESSED AS DATE)) AS DAYS_SINCE_ACCESS, COUNT(a.ACCESS_ID) AS ACCESS_COUNT_100D, ROUND(COUNT(a.ACCESS_ID) / 100, 4) AS ACCESS_FREQUENCY, ROUND((0.6665 * LN(TRUNC(SYSDATE - CAST(s.LAST_ACCESSED AS DATE)) + 1))/((COUNT(a.ACCESS_ID) / 100) + 0.01), 4) AS H_SCORE FROM SENSOR_READING s
LEFT JOIN DATA_ACCESS_LOG a ON s.READING_ID = a.READING_ID AND a.ACCESS_TIMESTAMP >= SYSTIMESTAMP - INTERVAL '100' DAY(3)
GROUP BY s.READING_ID, s.LAST_ACCESSED
ORDER BY H_SCORE DESC
FETCH FIRST 10 ROWS ONLY;

SELECT CASE
        WHEN H_SCORE < 25 THEN '0-25'
        WHEN H_SCORE < 50 THEN '25-50'
        WHEN H_SCORE < 100 THEN '50-100'
        WHEN H_SCORE < 150 THEN '100-150'
        WHEN H_SCORE < 250 THEN '150-250'
        ELSE '250+'
END AS SCORE_RANGE,
COUNT(*) AS RECORD_COUNT FROM (SELECT s.READING_ID, ROUND((0.6665 * LN(TRUNC(SYSDATE - CAST(s.LAST_ACCESSED AS DATE)) + 1))/ ((COUNT(a.ACCESS_ID) / 100) + 0.01), 4) AS H_SCORE FROM SENSOR_READING s
LEFT JOIN DATA_ACCESS_LOG a ON s.READING_ID = a.READING_ID AND a.ACCESS_TIMESTAMP >= SYSTIMESTAMP - INTERVAL '100' DAY(3)
GROUP BY s.READING_ID, s.LAST_ACCESSED)
GROUP BY CASE
        WHEN H_SCORE < 25 THEN '0-25'
        WHEN H_SCORE < 50 THEN '25-50'
        WHEN H_SCORE < 100 THEN '50-100'
        WHEN H_SCORE < 150 THEN '100-150'
        WHEN H_SCORE < 250 THEN '150-250'
        ELSE '250+'
END
ORDER BY MIN(H_SCORE);

